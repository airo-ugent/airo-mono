from __future__ import annotations

from typing import Any

from pydantic import BaseModel, field_validator


class Segment(BaseModel):
    id: str
    start: str
    stop: str
    url: str


class Segments(BaseModel):
    segment: Segment


class Owner(BaseModel):
    username: str
    email: str


class LabelItem(BaseModel):
    name: str
    color: str
    type: str
    attributes: Any


class Labels(BaseModel):
    label: list[LabelItem] | LabelItem


class Job(BaseModel):
    id: str
    name: str | None = None
    size: str
    mode: str
    overlap: str
    bugtracker: Any
    created: str
    updated: str
    subset: str
    start_frame: str
    stop_frame: str
    frame_filter: Any
    segments: Segments
    owner: Owner
    assignee: Any
    labels: Labels


class Meta(BaseModel):
    job: Job | None = None
    task: Job | None = None
    dumped: str

    def get_job_or_task(self) -> Job:
        if self.job:
            return self.job
        elif self.task:
            return self.task
        else:
            raise ValueError("No task or job found in meta. This should not happen")


class AnnotationItem(BaseModel):
    label: str
    source: str
    z_order: str
    occluded: str
    group_id: str | None = "1"  # set default group id to 1.


class Point(AnnotationItem):
    points: str

    @field_validator("points")
    @classmethod
    def has_two_coordinates(cls, v: str) -> str:
        if len(v.split(",")) != 2:
            raise ValueError("each point must be a single 2D coordinate for the AIRO flow.")
        return v


class Polygon(AnnotationItem):
    points: str


class Box(AnnotationItem):
    xtl: str
    ytl: str
    xbr: str
    ybr: str


class ImageItem(BaseModel):
    id: str
    name: str
    width: str
    height: str
    points: list[Point] | Point | None = None
    polygon: list[Polygon] | Polygon | None = None
    box: list[Box] | Box | None = None


class Annotations(BaseModel):
    version: str
    meta: Meta
    image: list[ImageItem]


class CVATImagesParser(BaseModel):
    annotations: Annotations


if __name__ == "__main__":
    import json
